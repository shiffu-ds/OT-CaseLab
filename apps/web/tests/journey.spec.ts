import { expect, test } from '@playwright/test';
import { mkdir, readFile } from 'node:fs/promises';
import { resolve } from 'node:path';

const root = resolve(__dirname, '../../..');
const screenshots = resolve(root, '.runtime/screenshots');
const password = 'Test-only-passphrase!2026';

async function register(page: import('@playwright/test').Page, prefix: string) {
  const email = `${prefix}-${Date.now()}@example.test`;
  await page.goto('/');
  await page.getByRole('button', { name: 'Create student account', exact: true }).click();
  await page.getByLabel('Full name', { exact: true }).fill('Practice Learner');
  await page.getByLabel('Email address', { exact: true }).fill(email);
  await page.getByLabel('Password', { exact: true }).fill(password);
  await page.getByRole('button', { name: 'Create student account', exact: true }).click();
  await expect(page.getByRole('heading', { name: /Welcome back, Practice/ })).toBeVisible();
  await expect(page.locator('.case-card')).toHaveCount(3);
  return email;
}

test('student completes a saved interview, image observation, plan and traceable report; Urdu and mobile render', async ({ page }) => {
  await mkdir(screenshots, { recursive: true });
  await page.goto('/');
  await expect(page.getByRole('heading', { name: 'Welcome to your studio.' })).toBeVisible();
  await page.screenshot({ path: resolve(screenshots, 'auth-desktop.png'), fullPage: true });
  const email = await register(page, 'journey');
  await page.screenshot({ path: resolve(screenshots, 'dashboard-desktop.png'), fullPage: true });
  await page.getByRole('button', { name: 'Begin a practice case' }).click();
  await expect(page.getByRole('tab', { name: /Interview/ })).toHaveAttribute('aria-selected', 'true');
  const initialMessages = await page.locator('.chat-message').count();
  await page.getByLabel('Your interview question').fill('What daily activity matters most to you, and what would you like to do for yourself at home?');
  await page.getByRole('button', { name: 'Send message', exact: true }).click();
  await expect(page.locator('.chat-message')).toHaveCount(initialMessages + 2);
  await expect(page.locator('.patient-message').last()).not.toContainText('undefined');
  await page.screenshot({ path: resolve(screenshots, 'interview-desktop.png'), fullPage: true });
  await page.getByRole('tab', { name: /Observe/ }).click();
  await expect(page.locator('.environment-image')).toBeVisible();
  await expect(page.locator('.environment-image')).toHaveJSProperty('complete', true);
  await expect(page.locator('.environment-image')).not.toHaveJSProperty('naturalWidth', 0);
  await page.getByLabel('Environment observations', { exact: true }).fill('I notice a chair, a shelf, a doorway and a table in the home image. I would ask which dressing location Ayesha prefers and obtain actual measurements before judging access. The image alone does not establish a fall risk.');
  await page.getByRole('button', { name: 'Save draft', exact: true }).click();
  await expect(page.getByRole('status').filter({ hasText: 'Your draft was saved.' })).toBeVisible();
  const assistance = page.waitForResponse(response => response.url().includes('/analysis') && response.request().method() === 'POST');
  await page.getByRole('button', { name: 'Request image assistance' }).click();
  expect((await assistance).ok()).toBeTruthy();
  await expect(page.locator('.analysis-result')).toContainText('Image assistance');
  // A PNG rendered from the repository's original fictional-room SVG tests the staged upload path.
  const image = await page.locator('.environment-image').screenshot();
  await page.getByLabel('Optional staged educational image').setInputFiles({ name: 'fictional-room.png', mimeType: 'image/png', buffer: image });
  const upload = page.waitForResponse(response => response.url().includes('/uploads') && response.request().method() === 'POST');
  await page.getByRole('button', { name: 'Upload for analysis' }).click();
  expect((await upload).ok()).toBeTruthy();
  await page.getByRole('tab', { name: /Build your plan/ }).click();
  await page.getByLabel(/Occupational profile/).fill('Ayesha values choosing her morning dressing routine after stroke. I would ask about her preferences, clothing, current assistance, household routines and priorities rather than assuming that independence means no support.');
  await page.getByLabel(/Patient-prioritized goals/).fill('Within two weeks, Ayesha will choose and complete her preferred morning dressing activity with agreed assistance on four of five mornings, using a chair if she prefers it. Confirm the goal and measure the activity with her.');
  await page.getByLabel(/Intervention rationale/).fill('I connect Ayesha\'s priority of dressing with the visible chair and surrounding home context. I would discuss graded practice and a workable clothing routine with her, check the space and requested assistance, and review progress. I cannot infer measurements or safety from one image; the proposed plan remains provisional.');
  await expect(page.locator('.evidence-item')).not.toHaveCount(0);
  await page.locator('.evidence-item input').first().check();
  await page.getByRole('button', { name: 'Submit for feedback' }).click();
  await expect(page.getByRole('heading', { name: 'Your reasoning, made visible.' })).toBeVisible();
  await expect(page.locator('.feedback-item')).toHaveCount(4);
  await expect(page.locator('.evidence-span')).not.toHaveCount(0);
  await expect(page.locator('.report')).not.toContainText('undefined');
  await page.screenshot({ path: resolve(screenshots, 'report-desktop.png'), fullPage: true });
  const downloadEvent = page.waitForEvent('download');
  await page.getByRole('link', { name: 'Download report' }).click();
  const download = await downloadEvent;
  expect(download.suggestedFilename()).toMatch(/\.md$/);
  expect(await download.failure()).toBeNull();
  await page.getByRole('tab', { name: /Build your plan/ }).click();
  await expect(page.getByLabel(/Occupational profile/)).toBeDisabled();
  await page.reload();
  await expect(page.getByRole('heading', { name: /Welcome back, Practice/ })).toBeVisible();
  await page.getByRole('button', { name: 'My learning', exact: true }).click();
  await page.getByRole('button', { name: 'View report' }).click();
  await expect(page.getByRole('heading', { name: 'Your reasoning, made visible.' })).toBeVisible();
  await page.getByRole('button', { name: 'Practice studio', exact: true }).click();
  await page.getByLabel('Practice language', { exact: true }).selectOption('ur');
  await expect(page.locator('html')).toHaveAttribute('dir', 'rtl');
  await expect(page.getByRole('heading', { name: /خوش آمدید/ })).toBeVisible();
  await page.screenshot({ path: resolve(screenshots, 'urdu-desktop.png'), fullPage: true });
  await page.getByLabel('Practice language', { exact: true }).selectOption('roman');
  await expect(page.locator('html')).toHaveAttribute('dir', 'ltr');
  await expect(page.getByRole('heading', { name: /Khush aamdeed/ })).toBeVisible();
  await page.getByLabel('Practice language', { exact: true }).selectOption('en');
  await page.setViewportSize({ width: 390, height: 844 });
  await page.screenshot({ path: resolve(screenshots, 'dashboard-mobile.png'), fullPage: true });
  const overflow = await page.evaluate(() => document.documentElement.scrollWidth > window.innerWidth);
  expect(overflow).toBe(false);
  await page.getByRole('button', { name: 'Open navigation' }).click();
  await expect(page.getByRole('button', { name: 'My learning', exact: true })).toBeVisible();
  await page.getByRole('button', { name: 'Sign out', exact: true }).click();
  await expect(page.getByRole('heading', { name: 'Welcome to your studio.' })).toBeVisible();
  await page.getByLabel('Email address', { exact: true }).fill(email);
  await page.getByLabel('Password', { exact: true }).fill(password);
  await page.getByRole('button', { name: 'Sign in', exact: true }).click();
  await expect(page.getByRole('heading', { name: /Welcome back, Practice/ })).toBeVisible();
});

test('educator reads authorized work and saves an attributed amendment', async ({ page }) => {
  const credentials = JSON.parse(await readFile(resolve(root, '.runtime/demo-credentials.json'), 'utf8'));
  await page.goto('/');
  await page.getByLabel('Email address', { exact: true }).fill(credentials.educator.email);
  await page.getByLabel('Password', { exact: true }).fill(credentials.educator.password);
  await page.getByRole('button', { name: 'Sign in', exact: true }).click();
  await page.getByRole('button', { name: 'Educator workspace', exact: true }).click();
  await expect(page.locator('.cohort-attempt')).not.toHaveCount(0);
  const submitted = page.locator('.cohort-attempt').filter({ hasText: /\d+\/\d+/ }).first();
  await submitted.click();
  await page.getByLabel('Your review and correction rationale').fill('I reviewed the student\'s exact submitted reasoning, patient priority and visible environment evidence. The coverage score is provisional; the student should confirm the goal with the person and obtain missing measurements.');
  await page.getByRole('button', { name: 'Save attributed review' }).click();
  await expect(page.getByRole('heading', { name: 'Educator feedback', exact: true })).toBeVisible();
  await expect(page.locator('.educator-review').last()).toContainText('exact submitted reasoning');
  await page.screenshot({ path: resolve(screenshots, 'educator-desktop.png'), fullPage: true });
  await page.getByRole('button', { name: /Case authoring/ }).click();
  await expect(page.locator('.source-case')).not.toHaveCount(0);
  await page.getByRole('button', { name: 'Create revision' }).first().click();
  await expect(page.getByLabel('Restricted case source JSON')).toHaveValue(/"rubric"/);
});

test('student controls optional consent and can delete their own account', async ({ page }) => {
  await register(page, 'privacy');
  await page.getByRole('button', { name: 'Account & privacy', exact: true }).click();
  await expect(page.locator('.consent-status')).toContainText('not granted');
  await page.getByRole('button', { name: 'Grant consent', exact: true }).click();
  await expect(page.locator('.consent-status')).toContainText('consent granted');
  await page.getByRole('button', { name: 'Withdraw consent', exact: true }).click();
  await expect(page.locator('.consent-status')).toContainText('not granted');
  await page.getByRole('button', { name: 'Review account deletion' }).click();
  await expect(page.getByRole('button', { name: 'Delete my account', exact: true })).toBeDisabled();
  await page.getByLabel('Type DELETE to confirm').fill('DELETE');
  await page.getByRole('button', { name: 'Delete my account', exact: true }).click();
  await expect(page.getByRole('heading', { name: 'Welcome to your studio.' })).toBeVisible();
  await page.reload();
  await expect(page.getByRole('heading', { name: 'Welcome to your studio.' })).toBeVisible();
});
